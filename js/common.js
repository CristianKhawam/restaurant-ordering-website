/* ---------- localStorage helpers ----------
   Storage can be blocked (private mode, browser settings), so every
   access is wrapped in try/catch and the site still works without it. */
function saveToStorage(key, value) {
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch (error) {
    console.warn("Could not save to localStorage:", error);
  }
}

function loadFromStorage(key, fallbackValue) {
  try {
    const storedText = localStorage.getItem(key);
    return storedText === null ? fallbackValue : JSON.parse(storedText);
  } catch (error) {
    console.warn("Could not read from localStorage:", error);
    return fallbackValue;
  }
}

function removeFromStorage(key) {
  try {
    localStorage.removeItem(key);
  } catch (error) {
    console.warn("Could not remove from localStorage:", error);
  }
}

/* ---------- Missing image fallback ----------
   While the AI images are not in /images yet, show a dotted
   placeholder with the alt text instead of a broken-image icon. */
function useImageFallback(imageElement) {
  const showPlaceholder = () => {
    const wrapper = imageElement.parentElement;
    wrapper.classList.add("img-missing");
    wrapper.dataset.missingText =
      imageElement.dataset.fallback || imageElement.alt || "Image coming soon";
    imageElement.hidden = true;
  };

  imageElement.addEventListener("error", showPlaceholder);

  // The image may have already failed before this script ran
  if (imageElement.complete && imageElement.naturalWidth === 0 && imageElement.src) {
    showPlaceholder();
  }
}

/* ---------- Footer: year, clock, credits ---------- */
function showCurrentYear() {
  const yearElement = document.getElementById("current-year");
  if (yearElement) {
    yearElement.textContent = new Date().getFullYear();
  }
}

const calgaryTimeFormatter = new Intl.DateTimeFormat("en-CA", {
  timeZone: CITY.timeZone,
  weekday: "short",
  hour: "2-digit",
  minute: "2-digit",
  second: "2-digit",
  hour12: true,
});

function updateClock() {
  const timeElement = document.getElementById("local-time");
  if (timeElement) {
    timeElement.textContent = calgaryTimeFormatter.format(new Date());
  }
}

