/* ---------- Weather (Open-Meteo, no API key needed) ---------- */
function buildWeatherUrl() {
  const params = new URLSearchParams({
    latitude: CITY.latitude,
    longitude: CITY.longitude,
    current: "temperature_2m,apparent_temperature,weather_code,wind_speed_10m",
    timezone: CITY.timeZone,
  });
  return `https://api.open-meteo.com/v1/forecast?${params}`;
}

async function loadWeather() {
  const summaryElement = document.getElementById("weather-summary");
  const detailsElement = document.getElementById("weather-details");
  if (!summaryElement || !detailsElement) return;

  try {
    const response = await fetch(buildWeatherUrl());
    if (!response.ok) {
      throw new Error(`Weather request failed (${response.status})`);
    }

    const weatherData = await response.json();
    const current = weatherData.current;
    const description = WEATHER_DESCRIPTIONS[current.weather_code] || {
      label: "Unknown conditions",
      icon: "🌡️",
    };

    summaryElement.textContent = `${description.icon} ${Math.round(current.temperature_2m)}°C · ${description.label}`;
    detailsElement.textContent = `Feels like ${Math.round(current.apparent_temperature)}°C · Wind ${Math.round(current.wind_speed_10m)} km/h`;
  } catch (error) {
    console.error(error);
    summaryElement.textContent = "Weather unavailable right now.";
    detailsElement.textContent = "Please check your connection and try again later.";
  }
}

/* ---------- Start everything shared ---------- */
function initCommon() {
  showCurrentYear();
  showImageCredits();

  updateClock();
  setInterval(updateClock, CLOCK_REFRESH_MS);

  loadWeather();
  setInterval(loadWeather, WEATHER_REFRESH_MS);

  document.querySelectorAll("img[data-fallback]").forEach(useImageFallback);
}

initCommon();
